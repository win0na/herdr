//! Pane palette loaded from an Xresources or Ghostty theme file.
//!
//! Herdr normally learns its terminal palette from a client attached to a
//! real terminal. A control stream is JSON over a pipe, so it cannot answer
//! OSC colour queries, and a pane that starts before its client attaches
//! would otherwise see Ghostty's built-in palette. This module builds a
//! terminal theme from a theme file so the server can answer those queries
//! itself.

use crate::terminal_theme::{RgbColor, TerminalTheme};

/// Load `terminal.palette`. A missing file, malformed colour, or missing
/// foreground/background is reported with the path and line so the config
/// diagnostic points at the problem.
pub(crate) fn load_terminal_theme(path: &str) -> Result<TerminalTheme, String> {
    let path = crate::worktree::expand_tilde_absolute_path(path);
    let source = std::fs::read_to_string(&path)
        .map_err(|err| format!("cannot read {}: {err}", path.display()))?;
    parse_terminal_theme(&source).map_err(|err| format!("{}: {err}", path.display()))
}

/// Parse an Xresources (`*.color1: #f38ba8`) or Ghostty
/// (`palette = 1=#f38ba8`) theme. The 16 base colours seed indices 0-15;
/// indices 16-255 are generated by Ghostty's CIELAB palette generator, with
/// explicitly configured entries preserved.
pub(crate) fn parse_terminal_theme(source: &str) -> Result<TerminalTheme, String> {
    let mut foreground = None;
    let mut background = None;
    let mut base = crate::ghostty::default_palette();
    let mut skip = [0u64; 4];
    let mut generate = true;
    let mut harmonious = false;

    for (line_index, raw_line) in source.lines().enumerate() {
        let line_number = line_index + 1;
        let line = raw_line.trim();
        if line.is_empty() || line.starts_with('!') || line.starts_with('#') {
            continue;
        }
        // Ghostty uses `key = value`; Xresources uses `key: value`.
        let Some((key, value)) = line
            .split_once('=')
            .or_else(|| line.split_once(':'))
            .map(|(key, value)| (key.trim(), value.trim()))
        else {
            continue;
        };
        if key.is_empty() || value.is_empty() {
            continue;
        }
        // Accept `*.color0`, `*color0`, and `color0`.
        let key = key
            .rsplit('*')
            .next()
            .unwrap_or(key)
            .trim()
            .trim_start_matches('.')
            .to_ascii_lowercase();
        let value = value.trim_matches('"');

        match key.as_str() {
            "foreground" => {
                foreground =
                    Some(parse_color(value).map_err(|err| format!("line {line_number}: {err}"))?);
            }
            "background" => {
                background =
                    Some(parse_color(value).map_err(|err| format!("line {line_number}: {err}"))?);
            }
            "palette-generate" => generate = parse_bool(value)?,
            "palette-harmonious" => harmonious = parse_bool(value)?,
            "palette" => {
                for entry in value.split([',', ' ']).filter(|entry| !entry.is_empty()) {
                    let Some((index, color)) = entry.split_once('=') else {
                        return Err(format!(
                            "line {line_number}: palette entry {entry:?} must be INDEX=#RRGGBB"
                        ));
                    };
                    let index = parse_palette_index(index.trim()).ok_or_else(|| {
                        format!("line {line_number}: invalid palette index {index:?}")
                    })?;
                    let color = parse_color(color.trim())
                        .map_err(|err| format!("line {line_number}: {err}"))?;
                    base[usize::from(index)] = to_ghostty_color(color);
                    set_palette_bit(&mut skip, index);
                }
            }
            _ => {
                if let Some(index) = key.strip_prefix("color").and_then(parse_palette_index) {
                    let color =
                        parse_color(value).map_err(|err| format!("line {line_number}: {err}"))?;
                    base[usize::from(index)] = to_ghostty_color(color);
                    set_palette_bit(&mut skip, index);
                }
            }
        }
    }

    let foreground = foreground.ok_or_else(|| "theme has no foreground colour".to_string())?;
    let background = background.ok_or_else(|| "theme has no background colour".to_string())?;
    let palette = if generate {
        crate::ghostty::generate_palette(
            &base,
            skip,
            to_ghostty_color(background),
            to_ghostty_color(foreground),
            harmonious,
        )
    } else {
        base
    };
    Ok(TerminalTheme {
        foreground: Some(foreground),
        background: Some(background),
        palette: palette.map(|color| Some(to_theme_color(color))),
    })
}

fn parse_palette_index(value: &str) -> Option<u8> {
    for (prefix, radix) in [("0x", 16), ("0o", 8), ("0b", 2)] {
        if let Some(digits) = value.strip_prefix(prefix) {
            return u8::from_str_radix(digits, radix).ok();
        }
    }
    value.parse().ok()
}

fn set_palette_bit(skip: &mut [u64; 4], index: u8) {
    skip[usize::from(index) >> 6] |= 1u64 << (index & 63);
}

fn parse_bool(value: &str) -> Result<bool, String> {
    match value.to_ascii_lowercase().as_str() {
        "true" | "yes" | "on" | "1" => Ok(true),
        "false" | "no" | "off" | "0" => Ok(false),
        _ => Err(format!("expected a boolean, got {value:?}")),
    }
}

fn parse_color(value: &str) -> Result<RgbColor, String> {
    let value = value.trim();
    if let Some(hex) = value.strip_prefix('#') {
        return parse_hex_color(hex).ok_or_else(|| format!("invalid colour {value:?}"));
    }
    if let Some(rgb) = value.strip_prefix("rgb:") {
        return parse_rgb_components(rgb).ok_or_else(|| format!("invalid colour {value:?}"));
    }
    match value.to_ascii_lowercase().as_str() {
        "black" => Ok(rgb(0, 0, 0)),
        "white" => Ok(rgb(255, 255, 255)),
        "red" => Ok(rgb(255, 0, 0)),
        "green" => Ok(rgb(0, 128, 0)),
        "blue" => Ok(rgb(0, 0, 255)),
        "yellow" => Ok(rgb(255, 255, 0)),
        "magenta" => Ok(rgb(255, 0, 255)),
        "cyan" => Ok(rgb(0, 255, 255)),
        "gray" | "grey" => Ok(rgb(128, 128, 128)),
        _ => Err(format!("invalid colour {value:?}")),
    }
}

fn parse_hex_color(hex: &str) -> Option<RgbColor> {
    let digits = hex.len() / 3;
    if !matches!(digits, 1..=4) || hex.len() != digits * 3 {
        return None;
    }
    if !hex.is_ascii() {
        return None;
    }
    let component = |part: &str| u8::from_str_radix(part, 16).ok();
    match digits {
        1 => {
            let r = component(&hex[0..1])? * 17;
            let g = component(&hex[1..2])? * 17;
            let b = component(&hex[2..3])? * 17;
            Some(rgb(r, g, b))
        }
        2 => {
            let r = component(&hex[0..2])?;
            let g = component(&hex[2..4])?;
            let b = component(&hex[4..6])?;
            Some(rgb(r, g, b))
        }
        3 | 4 => {
            // 12- or 16-bit components; keep the high 8 bits.
            let width = digits;
            let scale = |part: &str| {
                let value = u32::from_str_radix(part, 16).ok()?;
                let max = (1u32 << (width * 4)) - 1;
                Some(((value * 255 + max / 2) / max) as u8)
            };
            let r = scale(&hex[0..width])?;
            let g = scale(&hex[width..width * 2])?;
            let b = scale(&hex[width * 2..width * 3])?;
            Some(rgb(r, g, b))
        }
        _ => None,
    }
}

fn parse_rgb_components(components: &str) -> Option<RgbColor> {
    let mut parts = components.split('/');
    let scale = |part: &str| {
        if part.is_empty() || part.len() > 4 {
            return None;
        }
        let value = u32::from_str_radix(part, 16).ok()?;
        let max = (1u32 << (part.len() * 4)) - 1;
        Some(((value * 255 + max / 2) / max) as u8)
    };
    let r = scale(parts.next()?)?;
    let g = scale(parts.next()?)?;
    let b = scale(parts.next()?)?;
    (parts.next().is_none()).then_some(rgb(r, g, b))
}

const fn rgb(r: u8, g: u8, b: u8) -> RgbColor {
    RgbColor { r, g, b }
}

fn to_ghostty_color(color: RgbColor) -> crate::ghostty::RgbColor {
    crate::ghostty::RgbColor {
        r: color.r,
        g: color.g,
        b: color.b,
    }
}

fn to_theme_color(color: crate::ghostty::RgbColor) -> RgbColor {
    RgbColor {
        r: color.r,
        g: color.g,
        b: color.b,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const CATPPUCCIN_MOCHA: &str = r#"
! Catppuccin Mocha
*.foreground: #cdd6f4
*.background: #1e1e2e
*.color0:  #45475a
*.color1:  #f38ba8
*.color2:  #a6e3a1
*.color3:  #f9e2af
*.color4:  #89b4fa
*.color5:  #f5c2e7
*.color6:  #94e2d5
*.color7:  #bac2de
*.color8:  #585b70
*.color9:  #f38ba8
*.color10: #a6e3a1
*.color11: #f9e2af
*.color12: #89b4fa
*.color13: #f5c2e7
*.color14: #94e2d5
*.color15: #a6adc8
"#;

    #[test]
    fn parses_xresources_and_generates_the_same_palette_as_rootshell() {
        let theme = parse_terminal_theme(CATPPUCCIN_MOCHA).unwrap();
        assert_eq!(theme.foreground, Some(rgb(0xcd, 0xd6, 0xf4)));
        assert_eq!(theme.background, Some(rgb(0x1e, 0x1e, 0x2e)));
        assert_eq!(theme.palette[1], Some(rgb(0xf3, 0x8b, 0xa8)));
        assert_eq!(theme.palette[4], Some(rgb(0x89, 0xb4, 0xfa)));
        assert_eq!(theme.palette[8], Some(rgb(0x58, 0x5b, 0x70)));
        // Rootshel's generated palette answers OSC 4;196 with the base red.
        assert_eq!(theme.palette[196], Some(rgb(0xf3, 0x8b, 0xa8)));
        // The cube's first entry is the background, matching Ghostty and
        // rootshell's HerdrHostPalette generator.
        assert_eq!(theme.palette[16], Some(rgb(0x1e, 0x1e, 0x2e)));
        assert!(theme.palette.iter().all(Option::is_some));
    }

    #[test]
    fn preserves_explicit_palette_entries() {
        let theme = parse_terminal_theme(
            "foreground = #ffffff\nbackground = #000000\npalette = 196=#123456\n",
        )
        .unwrap();
        assert_eq!(theme.palette[196], Some(rgb(0x12, 0x34, 0x56)));
    }

    #[test]
    fn accepts_short_and_rgb_components() {
        let theme = parse_terminal_theme("foreground: #fff\nbackground: rgb:00/00/00\n").unwrap();
        assert_eq!(theme.foreground, Some(rgb(255, 255, 255)));
        assert_eq!(theme.background, Some(rgb(0, 0, 0)));
    }

    #[test]
    fn reports_missing_foreground_and_background() {
        assert_eq!(
            parse_terminal_theme("background: #000000\n").unwrap_err(),
            "theme has no foreground colour"
        );
        assert_eq!(
            parse_terminal_theme("foreground: #ffffff\n").unwrap_err(),
            "theme has no background colour"
        );
    }

    #[test]
    fn reports_a_bad_colour_with_its_line() {
        let err = parse_terminal_theme("foreground: #ffffff\ncolor1: #xyzxyz\n").unwrap_err();
        assert!(err.contains("line 2"), "{err}");
    }
}
